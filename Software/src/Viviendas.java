private void cargarViviendas() {

    DefaultTableModel modelo = (DefaultTableModel) tblViviendas.getModel();

    // Eliminar las filas anteriores
    modelo.setRowCount(0);

    String sql = "SELECT v.ID, v.DIRECCION, b.NOMBRE AS BARRIO, "
            + "COUNT(h.ID) AS TOTAL_HOGARES "
            + "FROM VIVIENDA v "
            + "JOIN BARRIO b ON v.ID_BARRIO = b.ID "
            + "LEFT JOIN HOGAR h ON h.ID_VIVIENDA = v.ID "
            + "GROUP BY v.ID, v.DIRECCION, b.NOMBRE "
            + "ORDER BY v.ID";

    try (Connection conexion = ConexionOracle.obtenerConexion()) {

        if (conexion == null) {
            JOptionPane.showMessageDialog(this,
                    "No se pudo conectar con Oracle.");
            return;
        }

        try (PreparedStatement ps = conexion.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {

            while (rs.next()) {

                int id = rs.getInt("ID");

                String ubicacion = rs.getString("DIRECCION")
                        + " - " + rs.getString("BARRIO");

                int hogares = rs.getInt("TOTAL_HOGARES");

                modelo.addRow(new Object[]{
                    id,
                    ubicacion,
                    hogares,
                    "Ver detalle"
                });
            }
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error al cargar viviendas:\n" + e.getMessage());
    }
}

