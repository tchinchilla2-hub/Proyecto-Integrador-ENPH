    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        String identificacion = txtIdentificacion.getText().trim();
String nombres = txtNombres.getText().trim();
String apellidos = txtApellidos.getText().trim();
String telefono = txtTelefono.getText().trim();

if (identificacion.isEmpty() || nombres.isEmpty()
        || apellidos.isEmpty() || telefono.isEmpty()) {

    JOptionPane.showMessageDialog(this,
            "Debe completar todos los campos obligatorios.");
    return;
}

if (identificacion.length() > 20 || nombres.length() > 80
        || apellidos.length() > 80 || telefono.length() > 20) {

    JOptionPane.showMessageDialog(this,
            "Uno de los campos supera la longitud permitida.");
    return;
}

try (Connection conexion = ConexionOracle.obtenerConexion()) {

    if (conexion == null) {
        JOptionPane.showMessageDialog(this,
                "No se pudo conectar con Oracle.");
        return;
    }

    String sqlVerificar =
            "SELECT COUNT(*) FROM ENCUESTADOR "
            + "WHERE NUM_IDENTIFICACION = ?";

    try (PreparedStatement ps = conexion.prepareStatement(sqlVerificar)) {
        ps.setString(1, identificacion);

        try (ResultSet rs = ps.executeQuery()) {
            if (rs.next() && rs.getInt(1) > 0) {
                JOptionPane.showMessageDialog(this,
                        "Ya existe un encuestador con esa identificación.");
                return;
            }
        }
    }

    int numero;

    try (PreparedStatement ps = conexion.prepareStatement(
            "SELECT SEQ_ENCUESTADOR.NEXTVAL FROM DUAL");
         ResultSet rs = ps.executeQuery()) {

        rs.next();
        numero = rs.getInt(1);
    }

    String codigo = String.format("ENC-%03d", numero);

    String sqlGuardar =
            "INSERT INTO ENCUESTADOR "
            + "(CODIGO, NUM_IDENTIFICACION, NOMBRE, APELLIDO, TELEFONO) "
            + "VALUES (?, ?, ?, ?, ?)";

    try (PreparedStatement ps = conexion.prepareStatement(sqlGuardar)) {

        ps.setString(1, codigo);
        ps.setString(2, identificacion);
        ps.setString(3, nombres);
        ps.setString(4, apellidos);
        ps.setString(5, telefono);

        int filas = ps.executeUpdate();

        if (filas == 1) {
            lblCodigoGenerado1.setText(codigo);

            JOptionPane.showMessageDialog(this,
                    "Encuestador registrado correctamente.\n"
                    + "Código asignado: " + codigo);
        }
    }

} catch (SQLException e) {

    JOptionPane.showMessageDialog(this,
            "Error al guardar en Oracle:\n" + e.getMessage(),
            "Error",
            JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_btnGuardarActionPerformed

