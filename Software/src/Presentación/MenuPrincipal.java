    private void FinalizarRecoleccionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_FinalizarRecoleccionActionPerformed
        int respuesta = javax.swing.JOptionPane.showConfirmDialog(this,
                "¿Desea cerrar definitivamente la encuesta del hogar?\n"
                + "Debe haberse cumplido el periodo de 14 días y revisado todos los gastos.",
                "Confirmar finalización", javax.swing.JOptionPane.YES_NO_OPTION);
        if (respuesta != javax.swing.JOptionPane.YES_OPTION) return;
        try {
            new software.Main().finalizarRecoleccion();
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Recolección finalizada y guardada en Oracle.");
            PresentacionCierre ventana = new PresentacionCierre();
            ventana.setLocationRelativeTo(null);
            ventana.setVisible(true);
            this.dispose();
        } catch (RuntimeException ex) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "No fue posible finalizar la recolección:\n" + ex.getMessage(),
                    "Cierre no realizado", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_FinalizarRecoleccionActionPerformed

