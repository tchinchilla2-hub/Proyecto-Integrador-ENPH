    private void actualizarFechaActual() {
    LocalDate fechaActual = LocalDate.now();

    DateTimeFormatter formato = DateTimeFormatter.ofPattern(
        "dd 'de' MMMM 'de' yyyy",
        new Locale("es", "CO")
    );

    lblFecha.setText(fechaActual.format(formato));
}
