    private void SiguienteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SiguienteActionPerformed
        // TODO add your handling code here:
        
    String nombre = NombreAlimento.getText().trim();
    String cantidadTexto = Cantidad.getText().trim();
    String contenidoTexto = Contenido.getText().trim();

    // Verificar los campos obligatorios
    if (nombre.isEmpty() || cantidadTexto.isEmpty()
            || Unidad.getSelectedIndex() == 0) {

        javax.swing.JOptionPane.showMessageDialog(this,"Debe completar los campos obligatorios");
        return;
    }

    // Validar cantidad adquirida
    double cantidad;

    try {
        cantidad = Double.parseDouble(
                cantidadTexto.replace(",", "."));

        if (!Double.isFinite(cantidad) || cantidad <= 0) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "La cantidad debe ser mayor que cero");
            return;
        }

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Ingrese una cantidad válida");
        return;
    }

    // Verificar presentación solamente si seleccionó Unidad
    String unidadSeleccionada =
            Unidad.getSelectedItem().toString();

    double contenido = 0;

    if (unidadSeleccionada.equals("Unidad")) {

        if (!contenidoTexto.isEmpty()) {

            try {
                contenido = Double.parseDouble(
                        contenidoTexto.replace(",", "."));

                if (!Double.isFinite(contenido) || contenido <= 0) {
                    javax.swing.JOptionPane.showMessageDialog(this,
                            "El contenido debe ser mayor que cero");
                    return;
                }

            } catch (NumberFormatException e) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Ingrese un contenido válido");
                return;
            }

            if (UnidadContenido.getSelectedIndex() == 0) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Seleccione la unidad del contenido");
                return;
            }

        } else if (UnidadContenido.getSelectedIndex() != 0) {

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Ingrese el contenido por unidad");
            return;
        }
    }

    // Crear objeto GastoDiario
    GastoDiario gasto = new GastoDiario();

    // Guardar información del alimento
    gasto.nombreAlimento = nombre;
    gasto.cantidad = cantidad;
    gasto.unidadMedida = unidadSeleccionada;

    // Guardar presentación por unidad, si se diligenció
    if (unidadSeleccionada.equals("Unidad")
            && !contenidoTexto.isEmpty()) {

        gasto.contenidoUnidad = contenido;
        gasto.unidadContenido =
                UnidadContenido.getSelectedItem().toString();
    }

    // Enviar los datos al siguiente formulario
    AdquisiciónClasificación ventana =new AdquisiciónClasificación(gasto);

    ventana.setLocationRelativeTo(null);
    ventana.setVisible(true);

    // Cerrar formulario actual
    this.dispose();
    }//GEN-LAST:event_SiguienteActionPerformed

    private void UnidadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_UnidadActionPerformed
        // TODO add your handling code here:
        String unidadSeleccionada=Unidad.getSelectedItem().toString();
        if(unidadSeleccionada.equals("Unidad")){
            // habilitar presentación por unidad
            Contenido.setEnabled(true);
            UnidadContenido.setEnabled(true);
           
        }else{
            //Desahabilitar presentación por unidad
            Contenido.setEnabled(false);
            UnidadContenido.setEnabled(false);
            
            //Limpiar los datos anteriores
            Contenido.setText("");
            UnidadContenido.setSelectedIndex(0);
        }
    }//GEN-LAST:event_UnidadActionPerformed

