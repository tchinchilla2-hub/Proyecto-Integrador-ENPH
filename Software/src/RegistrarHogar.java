private void cargarViviendas() {

    cmbVivienda.removeAllItems();
    cmbVivienda.addItem("Seleccione una vivienda");

    String sql = "SELECT v.ID, v.DIRECCION, b.NOMBRE AS BARRIO "
            + "FROM VIVIENDA v "
            + "JOIN BARRIO b ON v.ID_BARRIO = b.ID "
            + "ORDER BY v.ID";

    try (Connection conexion = ConexionOracle.obtenerConexion()) {

        if (conexion == null) {
            JOptionPane.showMessageDialog(this,
                    "No se pudo conectar con Oracle.");
            return;
        }

        try (PreparedStatement ps = conexion.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {

            while (rs.next()) {

                int id = rs.getInt("ID");
                String direccion = rs.getString("DIRECCION");
                String barrio = rs.getString("BARRIO");

                cmbVivienda.addItem(
                        id + " - " + direccion + " - " + barrio
                );
            }
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error al cargar viviendas:\n" + e.getMessage());
    }
}


