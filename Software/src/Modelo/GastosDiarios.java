// Esta clase respresenta lso datos de un gasto. Mas adelante la podremos utilizar para insertar la informacion en Oracle
public class GastosDiarios {
private int id;
    private String nombreAlimento;
    private double cantidad;
    private String unidadMedida;
    private double contenidoUnidad;
    private String unidadContenido;

    private String formaAdquisicion;
    private String frecuenciaCompra;
    private String lugarCompra;
    private String tipoGasto;
    private double valorPagado;

    private LocalDate fecha;
    private Encuesta encuesta;

    public GastosDiarios() {
        this.fecha = LocalDate.now();
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getNombreAlimento() {
        return nombreAlimento;
    }

    public void setNombreAlimento(String nombreAlimento) {
        this.nombreAlimento = nombreAlimento;
    }

    public double getCantidad() {
        return cantidad;
    }

    public void setCantidad(double cantidad) {
        this.cantidad = cantidad;
    }

    public String getUnidadMedida() {
        return unidadMedida;
    }

    public void setUnidadMedida(String unidadMedida) {
        this.unidadMedida = unidadMedida;
    }

    public double getContenidoUnidad() {
        return contenidoUnidad;
    }

    public void setContenidoUnidad(double contenidoUnidad) {
        this.contenidoUnidad = contenidoUnidad;
    }

    public String getUnidadContenido() {
        return unidadContenido;
    }

    public void setUnidadContenido(String unidadContenido) {
        this.unidadContenido = unidadContenido;
    }

    public String getFormaAdquisicion() {
        return formaAdquisicion;
    }

    public void setFormaAdquisicion(String formaAdquisicion) {
        this.formaAdquisicion = formaAdquisicion;
    }

    public String getFrecuenciaCompra() {
        return frecuenciaCompra;
    }

    public void setFrecuenciaCompra(String frecuenciaCompra) {
        this.frecuenciaCompra = frecuenciaCompra;
    }

    public String getLugarCompra() {
        return lugarCompra;
    }

    public void setLugarCompra(String lugarCompra) {
        this.lugarCompra = lugarCompra;
    }

    public String getTipoGasto() {
        return tipoGasto;
    }

    public void setTipoGasto(String tipoGasto) {
        this.tipoGasto = tipoGasto;
    }

    public double getValorPagado() {
        return valorPagado;
    }

    public void setValorPagado(double valorPagado) {
        this.valorPagado = valorPagado;
    }

    public LocalDate getFecha() {
        return fecha;
    }

    public void setFecha(LocalDate fecha) {
        this.fecha = fecha;
    }

    public Encuesta getEncuesta() {
        return encuesta;
    }

    public void setEncuesta(Encuesta encuesta) {
        this.encuesta = encuesta;
    }
}
