    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
    // Obtener los datos del formulario
    String identificacion = txtIdentificacion.getText().trim();
    String nombres = txtNombres.getText().trim();
    String apellidos = txtApellidos.getText().trim();
    String telefono = txtTelefono.getText().trim();

    try (java.sql.Connection conexion =ConexionOracle.obtenerConexion()) {

        if (conexion == null) {
            JOptionPane.showMessageDialog(this,
                    "No se pudo conectar con Oracle.");
            return;
        }

        // Llamar a la capa de negocio
        EncuestadorService servicio =
                new EncuestadorService();

        servicio.registrarEncuestador(
                conexion,
                identificacion,
                nombres,
                apellidos,
                telefono
        );

        JOptionPane.showMessageDialog(this,"Encuestador registrado correctamente.\n" + "Identificación: " + identificacion);

        // Limpiar los campos después del registro
        txtIdentificacion.setText("");
        txtNombres.setText("");
        txtApellidos.setText("");
        txtTelefono.setText("");

    } catch (IllegalArgumentException e) {

        JOptionPane.showMessageDialog(this,
                e.getMessage(),
                "Validación",
                JOptionPane.WARNING_MESSAGE);

    } catch (java.sql.SQLException e) {

        JOptionPane.showMessageDialog(this,
                "Error al registrar encuestador:\n"
                + e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnGuardarActionPerformed

