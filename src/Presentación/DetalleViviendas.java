private void cargarDetalleVivienda() {

    String sql = "SELECT v.ID, v.DIRECCION, "
            + "b.NOMBRE AS BARRIO "
            + "FROM VIVIENDA v "
            + "JOIN BARRIO b ON v.ID_BARRIO = b.ID "
            + "WHERE v.ID = ?";

    try (Connection conexion = ConexionOracle.obtenerConexion()) {

        if (conexion == null) {
            JOptionPane.showMessageDialog(this,
                    "No se pudo conectar con Oracle.");
            return;
        }

        try (PreparedStatement ps = conexion.prepareStatement(sql)) {

            ps.setInt(1, idVivienda);

            try (ResultSet rs = ps.executeQuery()) {

                if (rs.next()) {

                    lblCodigoVivienda.setText(
                            "Vivienda " + rs.getInt("ID"));

                    lblDireccion.setText(
                            rs.getString("DIRECCION"));

                    lblBarrio.setText(
                            rs.getString("BARRIO"));

                } else {
                    JOptionPane.showMessageDialog(this,
                            "No se encontró la vivienda seleccionada.");
                }
            }
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error al consultar la vivienda:\n"
                + e.getMessage());
    }
}
