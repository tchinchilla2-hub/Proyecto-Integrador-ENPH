    private void cargarResultados() {

    DefaultTableModel modelo =
            (DefaultTableModel) tblResultados.getModel();

    modelo.setColumnIdentifiers(new Object[]{
        "Hogar",
        "Jefe del hogar",
        "Encuestador",
        "Ubicación",
        "Primera visita"
    });

    modelo.setRowCount(0);

    String sql =
        "SELECT h.ID, "
        + "j.NOMBRE AS NOMBRE_JEFE, "
        + "j.APELLIDO AS APELLIDO_JEFE, "
        + "e.NOMBRE AS NOMBRE_ENCUESTADOR, "
        + "e.APELLIDO AS APELLIDO_ENCUESTADOR, "
        + "v.DIRECCION, "
        + "b.NOMBRE AS BARRIO "
        + "FROM HOGAR h "
        + "JOIN JEFE_HOGAR j "
        + "ON j.ID_HOGAR = h.ID "
        + "JOIN ENCUESTADOR e "
        + "ON e.NUM_IDENTIFICACION = "
        + "h.NUM_IDENTIFICACION_ENCUESTADOR "
        + "JOIN VIVIENDA v "
        + "ON v.ID = h.ID_VIVIENDA "
        + "JOIN BARRIO b "
        + "ON b.ID = v.ID_BARRIO "
        + "WHERE h.NUM_IDENTIFICACION_ENCUESTADOR IS NOT NULL "
        + "ORDER BY h.ID";

    try (Connection conexion =
            ConexionOracle.obtenerConexion()) {

        if (conexion == null) {
            JOptionPane.showMessageDialog(this,
                    "No se pudo conectar con Oracle.");
            return;
        }

        try (PreparedStatement ps =
                conexion.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {

            while (rs.next()) {

                int idHogar = rs.getInt("ID");

                String jefeHogar =
                        rs.getString("NOMBRE_JEFE") + " "
                        + rs.getString("APELLIDO_JEFE");

                String encuestador =
                        rs.getString("NOMBRE_ENCUESTADOR") + " "
                        + rs.getString("APELLIDO_ENCUESTADOR");

                String ubicacion =
                        rs.getString("BARRIO") + " - "
                        + rs.getString("DIRECCION");


                modelo.addRow(new Object[]{
                    jefeHogar,
                    encuestador,
                    ubicacion,
                    "Pendiente"
                });
            }
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error al cargar resultados:\n"
                + e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE);
    }
}

