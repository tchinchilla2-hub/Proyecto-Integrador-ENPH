    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        // INGRESO DEL ENCUESTADOR
    if (rbEncuestador.isSelected()) {

        // Solicitar la identificación del encuestador
        String identificacion =
                javax.swing.JOptionPane.showInputDialog(
                        this,
                        "Ingrese su número de identificación:",
                        "Acceso del encuestador",
                        javax.swing.JOptionPane.QUESTION_MESSAGE
                );

        // Comprobar si canceló
        if (identificacion == null) {
            return;
        }

        identificacion = identificacion.trim();

        // Comprobar que no esté vacío
        if (identificacion.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Debe ingresar su número de identificación."
            );
            return;
        }

        // Buscar el encuestador en Oracle
        String sql =
                "SELECT CODIGO, NOMBRE, APELLIDO "
                + "FROM ENCUESTADOR "
                + "WHERE NUM_IDENTIFICACION = ?";

        try (java.sql.Connection con =
                ConexionOracle.obtenerConexion()) {

            if (con == null) {
                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "No se pudo conectar con Oracle."
                );
                return;
            }

            try (java.sql.PreparedStatement ps =
                    con.prepareStatement(sql)) {

                ps.setString(1, identificacion);

                try (java.sql.ResultSet rs =
                        ps.executeQuery()) {

                    if (rs.next()) {

                        // Obtener el código real del encuestador
                        String codigoEncuestador =
                                rs.getString("CODIGO");

                        String nombreCompleto =
                                rs.getString("NOMBRE") + " "
                                + rs.getString("APELLIDO");

                        javax.swing.JOptionPane.showMessageDialog(
                                this,
                                "Bienvenido, " + nombreCompleto
                        );

                        // Abrir el cronograma del encuestador
                        CronogramaVisitas ventana =
                                new CronogramaVisitas(
                                        codigoEncuestador
                                );

                        ventana.setLocationRelativeTo(null);
                        ventana.setVisible(true);

                        this.dispose();

                    } else {

                        javax.swing.JOptionPane.showMessageDialog(
                                this,
                                "No se encontró un encuestador "
                                + "registrado con esa identificación."
                        );
                    }
                }
            }

        } catch (java.sql.SQLException e) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Error al consultar Oracle: "
                    + e.getMessage()
            );
        }

    // INGRESO DEL ADMINISTRADOR
    } else if (rbAdministrador.isSelected()) {

        MenuPrincipalOficina menu =
                new MenuPrincipalOficina();

        menu.setLocationRelativeTo(null);
        menu.setVisible(true);

        this.dispose();

    // INGRESO DEL JEFE DE HOGAR
    } else if (rbJefeHogar.isSelected()) {
javax.swing.JTextField txtIdentificacion =
            new javax.swing.JTextField(18);

    javax.swing.JPasswordField txtContrasena =
            new javax.swing.JPasswordField(18);

    txtContrasena.setEchoChar('*');

    javax.swing.JPanel panel = new javax.swing.JPanel(
            new java.awt.GridLayout(4, 1, 5, 5)
    );

    panel.add(new javax.swing.JLabel("Número de identificación:"));
    panel.add(txtIdentificacion);

    panel.add(new javax.swing.JLabel("Contraseña:"));
    panel.add(txtContrasena);

    int opcion = javax.swing.JOptionPane.showConfirmDialog(
            this,
            panel,
            "Acceso del jefe de hogar",
            javax.swing.JOptionPane.OK_CANCEL_OPTION,
            javax.swing.JOptionPane.PLAIN_MESSAGE
    );

    if (opcion != javax.swing.JOptionPane.OK_OPTION) {
        return;
    }

    String identificacion = txtIdentificacion.getText().trim();
    String contrasena = new String(txtContrasena.getPassword());

    if (identificacion.isEmpty() || contrasena.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Ingrese la identificación y la contraseña."
        );
        return;
    }

    // Contraseña inicial del jefe de hogar
    if (!identificacion.equals(contrasena)) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Identificación o contraseña incorrecta."
        );
        return;
    }

    // Comprobar que existe una encuesta activa
    String sql =
            "SELECT h.ID, e.FECHA_INICIO "
            + "FROM JEFE_HOGAR j "
            + "JOIN HOGAR h ON j.ID_HOGAR = h.ID "
            + "JOIN ENCUESTA e ON e.ID_HOGAR = h.ID "
            + "WHERE j.NUM_IDENTIFICACION = ? "
            + "AND e.ESTADO_ENCUESTA = 'EN PROCESO' "
            + "AND e.FECHA_CIERRE IS NULL "
            + "ORDER BY e.ID DESC";

    try (java.sql.Connection con =
            ConexionOracle.obtenerConexion()) {

        if (con == null) {
            throw new java.sql.SQLException(
                    "No se pudo conectar con Oracle."
            );
        }

        try (java.sql.PreparedStatement ps =
                con.prepareStatement(sql)) {

            ps.setString(1, identificacion);

            try (java.sql.ResultSet rs = ps.executeQuery()) {

                if (rs.next()) {

                    int idHogar = rs.getInt("ID");

                    java.sql.Date fechaInicio =
                            rs.getDate("FECHA_INICIO");

                    String codigoHogar =
                            String.format("HG-%03d", idHogar);

                    // Mantener la sesión del jefe de hogar
                    DatosRecoleccion.iniciarRecoleccion(
                            codigoHogar,
                            fechaInicio.toLocalDate()
                    );

                    MenuPrincipal menu = new MenuPrincipal();

                    menu.setLocationRelativeTo(null);
                    menu.setVisible(true);

                    this.dispose();

                } else {

                    javax.swing.JOptionPane.showMessageDialog(
                            this,
                            "No se encontró una encuesta activa "
                            + "para esta identificación."
                    );
                }
            }
        }

    } catch (java.sql.SQLException e) {
    javax.swing.JOptionPane.showMessageDialog(
                this,
                "Error al consultar Oracle:\n" + e.getMessage()
        );
    }

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Seleccione un tipo de usuario." );
    }
    }//GEN-LAST:event_jButton1ActionPerformed

